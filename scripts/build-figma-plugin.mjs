#!/usr/bin/env node
/**
 * Builds figma-plugin/code.js from figma-plugin/kit.json (components), figma-plugin/annotation-tokens.json
 * (variables, colors, fonts, identity), and the sources in figma-plugin/src/.
 * Figma plugins can't read files, so the data is embedded. It also regenerates the token sections of
 * docs/reference/annotation-kit.md. --check fails if code.js or those sections are stale.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { loadTokens, tokensIdentity, figmaVariables, docBlock, withDocBlock, DOC_FILE } from './lib/annotation.mjs';

const dir = join(dirname(new URL(import.meta.url).pathname), '..', 'figma-plugin');
const kit = JSON.parse(readFileSync(join(dir, 'kit.json'), 'utf-8'));
const tokens = loadTokens(join(dir, 'annotation-tokens.json'));
kit.variables = figmaVariables(tokens);
kit.tokens = { ...tokensIdentity(tokens), typography: tokens.typography };
const out = [
  '/* Generated by scripts/build-figma-plugin.mjs from kit.json and src/. Do not edit by hand. */',
  'const KIT = ' + JSON.stringify(kit) + ';',
  readFileSync(join(dir, 'src', 'kit-builder.js'), 'utf-8'),
  readFileSync(join(dir, 'src', 'plugin.js'), 'utf-8'),
].join('\n');
const target = join(dir, 'code.js');
const doc = existsSync(DOC_FILE) ? readFileSync(DOC_FILE, 'utf-8') : '';
const nextDoc = withDocBlock(doc, docBlock(tokens));
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(target, 'utf-8'); } catch { /* missing counts as stale */ }
  if (current !== out) { console.error('FAIL: figma-plugin/code.js is out of date. Run: npm run build:figma-plugin'); process.exit(1); }
  if (doc !== nextDoc) { console.error('FAIL: the token sections of docs/reference/annotation-kit.md are out of date. Run: npm run build:figma-plugin'); process.exit(1); }
  console.log('figma-plugin/code.js and the annotation-kit token sections are up to date.');
} else {
  writeFileSync(target, out);
  writeFileSync(DOC_FILE, nextDoc);
  console.log(`Wrote ${target} (${kit.components.length} components, ${out.length} bytes) and the token sections of ${DOC_FILE}.`);
}
